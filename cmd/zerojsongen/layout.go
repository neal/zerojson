// Arena and fuzz helper names are package-wide. Until split outputs have an
// explicit shared-helper ownership model, refuse them before writing files.
// Regenerating the same codec/test pair remains supported.
func guardOutputLayout(dir, out, testsOut string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		log.Fatal(err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments|parser.PackageClauseOnly)
		if err != nil || !hasZeroJSONHeader(f) {
			continue
		}
		if strings.HasSuffix(entry.Name(), "_test.go") {
			if testsOut == "" {
				// Left over from a run that passed -tests: it would keep
				// testing the OLD codec (and stop compiling after a type
				// rename) while looking like current output.
				log.Fatalf("%s is generated fuzz tests from a previous -tests run and would go stale — pass -tests %s again to regenerate it with the codec, or delete it", path, entry.Name())
			}
			if !samePath(path, testsOut) {
				log.Fatalf("multiple zerojson test outputs in one package are not supported (%s and %s) — reuse the existing -tests file", path, testsOut)
			}
		} else if !samePath(path, out) {
			log.Fatalf("multiple zerojson codec outputs in one package are not supported (%s and %s) — combine -types into one -out file", path, out)
		}
	}
}

func hasZeroJSONHeader(f *ast.File) bool {
	for _, group := range f.Comments {
		if group.End() >= f.Package {
			continue
		}
		for _, c := range group.List {
			if strings.TrimSpace(c.Text) == "// Code generated by zerojsongen. DO NOT EDIT." {
				return true
			}
		}
	}
	return false
}

// An exported field can expose a type the consuming package cannot name.
// Its value is accessible to reflection, but not to our emitted casts/arena
// declarations. Refuse that shape rather than reporting generation success.
// An exported alias is sufficient: validate its spelling, not its RHS.
func (g *generator) checkTypeVisibility(t types.Type) {
	if g.pkg == nil || g.pkg.Types == nil {
		return
	}
	check := func(obj *types.TypeName, args *types.TypeList) {
		if obj.Pkg() != nil && obj.Pkg() != g.pkg.Types && !obj.Exported() {
			log.Fatalf("cannot name unexported type %s.%s in generated code — expose an exported alias or generate the codec in its declaring package", obj.Pkg().Path(), obj.Name())
		}
		for i := 0; i < args.Len(); i++ {
			g.checkTypeVisibility(args.At(i))
		}
	}
	switch t := t.(type) {
	case *types.Named:
		check(t.Obj(), t.TypeArgs())
	case *types.Alias:
		check(t.Obj(), t.TypeArgs())
	case *types.Pointer:
		g.checkTypeVisibility(t.Elem())
	case *types.Slice:
		g.checkTypeVisibility(t.Elem())
	case *types.Array:
		g.checkTypeVisibility(t.Elem())
	case *types.Map:
		g.checkTypeVisibility(t.Key())
		g.checkTypeVisibility(t.Elem())
	}
}

// Fuzz templates use fixed standard-library qualifiers. Rename only actual
// import selectors (never string literals) if a package-scope user identifier
// would collide. Pick aliases absent from both the target and generated file.
func (g *generator) aliasTestImports(src string) string {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "generated_test.go", src, parser.ParseComments)
	if err != nil {
		log.Fatalf("parse generated tests: %v", err)
	}
	used := map[string]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		if id, ok := n.(*ast.Ident); ok {
			used[id.Name] = true
		}
		return true
	})
	renames := map[string]string{}
	for _, imp := range f.Imports {
		path, _ := strconv.Unquote(imp.Path.Value)
		name := filepath.Base(path)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if name == "_" || name == "." || g.pkg.Types.Scope().Lookup(name) == nil {
			continue
		}
		if path == runtimePath {
			log.Fatal("target package declares the reserved runtime import name zerojson")
		}
		alias := name + "_"
		for used[alias] || g.pkg.Types.Scope().Lookup(alias) != nil {
			alias += "_"
		}
		used[alias] = true
		renames[name] = alias
		imp.Name = ast.NewIdent(alias)
	}
	if len(renames) == 0 {
		return src
	}
	ast.Inspect(f, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok && id.Obj == nil {
				if alias, ok := renames[id.Name]; ok {
					id.Name = alias
				}
			}
		}
		return true
	})
	var out strings.Builder
	if err := format.Node(&out, fset, f); err != nil {
		log.Fatal(fmt.Errorf("format aliased tests: %w", err))
	}
	return out.String()
}
