package main

import (
	"go/ast"
	"go/parser"
	"go/token"
	"testing"
)

func TestReplaceableCodecOutputIsGeneratorSpecific(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{
			name: "zerojsongen",
			src:  "// Code generated by zerojsongen. DO NOT EDIT.\npackage p\n",
			want: true,
		},
		{
			name: "easyjson",
			src:  "// Code generated by easyjson for marshaling/unmarshaling. DO NOT EDIT.\npackage p\n",
			want: true,
		},
		{
			name: "other generator with custom wire methods",
			src:  "// Code generated by schema-tool. DO NOT EDIT.\npackage p\n",
			want: false,
		},
		{
			name: "quoted zerojsongen marker in package docs",
			src:  "package p\n\n// Documentation example: Code generated by zerojsongen. DO NOT EDIT.\ntype T struct{}\n",
			want: false,
		},
		{
			name: "exact marker after package",
			src:  "package p\n\n// Code generated by zerojsongen. DO NOT EDIT.\ntype T struct{}\n",
			want: false,
		},
		{
			name: "near prefix is not the generator header",
			src:  "// Code generated by zerojsongen. DO NOT EDIT. This file is handwritten.\npackage p\n",
			want: false,
		},
		{
			name: "handwritten",
			src:  "package p\n",
			want: false,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			file, err := parser.ParseFile(token.NewFileSet(), "fixture.go", tc.src, parser.ParseComments)
			if err != nil {
				t.Fatal(err)
			}
			if tc.name == "other generator with custom wire methods" && !ast.IsGenerated(file) {
				t.Fatal("test setup: standard generated marker was not recognized")
			}
			if got := isReplaceableCodecOutput(file); got != tc.want {
				t.Fatalf("isReplaceableCodecOutput()=%v, want %v", got, tc.want)
			}
		})
	}
}
